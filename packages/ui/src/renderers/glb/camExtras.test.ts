import { Group, Mesh } from 'three';
import { expect, it } from 'vitest';
import { camSourcePath, carriesCamJob, formatDuration, jobSummary, operationDetail, readCamJob, toolChangeWords, toolSpeeds } from '../../../dist/renderers/glb/cam/extras.js';
import { camExtras, camScene } from './__tests__/camFile';

it('reads the job a ready result carries: verdict, setups, operations, tools, posts and what it assumed', () => {
  const job = readCamJob(camScene())!;
  expect(job.verdict).toEqual({ status: 'ready', headline: 'Ready to cut · 2 min · 2 tools', errors: 0, warnings: 0, gcode: '' });
  expect(job.setups.map((setup: any) => [setup.id, setup.plain, setup.orientation, setup.axis, setup.timeS, setup.operations.map((op: any) => op.op)]))
    .toEqual([['top', 'top', '+Z', [0, 0, 1], 129.53, ['face', 'pocket', 'profile', 'drill']]]);
  expect(job.operations[1]).toEqual({ index: 1, op: 'pocket', plain: 'Pocket', name: '', tool: 'T1', toolPlain: '6 mm flat', toolDiameterMm: 6,
    toolType: 'flat', rpm: 13260, feedMmMin: 1083, timeS: 19.24, t0: 62.478, t1: 81.717,
    summary: 'Pocket COMPOUND/face 17 with T1 6 mm flat, 19 s', faces: ['COMPOUND/face 17'], setup: 'top' });
  expect(job.operations[3].toolType).toBe('drill');
  expect(job).toMatchObject({ durationS: 129.533, document: 'bracket.step', post: 'grbl', findings: [] });
  expect(job.posts).toEqual([{ setup: 'top', file: 'bracket.top.1-T1.nc', post: 'grbl', tool: 'T1' }, { setup: 'top', file: 'bracket.top.2-T2.nc', post: 'grbl', tool: 'T2' }]);
  expect(operationDetail(job.operations[0])).toBe('6 mm flat · 1 min');
  expect(job.assumed[0]).toEqual({ key: 'machine.rapid_mm_min', value: '3000', why: 'for the cycle time only' });
  expect(job.assumed).toHaveLength(5);
  expect(job.safety).toMatch(/^Generated by cadgen with FreeCAD; not proven on a machine\./);
});

it('reads a refused result: its verdict, its error with the operation and place it names, a -Z setup\'s axis', () => {
  const job = readCamJob(camScene({ extras: camExtras('fix') }))!;
  expect(job.verdict).toEqual({ status: 'fix', headline: '1 to fix · 30 s · 1 tool', errors: 1, warnings: 0, gcode: 'G-code not written: fix 1 error first' });
  expect(job.setups.map((setup: any) => [setup.id, setup.orientation, setup.axis])).toEqual([['top', '+Z', [0, 0, 1]], ['bottom', '-Z', [0, 0, -1]]]);
  expect(job.findings).toEqual([{ check: 'reach', level: 'error', message: expect.stringContaining('27% of COMPOUND/face 9 is under the part'),
    operation: 0, operations: [0], at: [3.333, 2.444, -13.95] }]);
  expect(job.posts).toEqual([]);
  expect(jobSummary(job)).toBe('No tool changes · linuxcnc controller');
});

it('is no job for a plain GLB, nor for one that only names the generator or only carries extras', () => {
  const plain = new Group();
  plain.add(new Mesh());
  expect(carriesCamJob(plain)).toBe(false);
  expect(readCamJob(plain)).toBeNull();
  expect(readCamJob(camScene({ extras: null }))).toBeNull();
  expect(readCamJob(camScene({ generator: '' }))).toBeNull();
  expect(readCamJob(null)).toBeNull();
});

it('reads a damaged job forgivingly: plain defaults, a finding with nothing to say left out, a verdict that is not ready', () => {
  const root = camScene({ extras: { setups: [{ operations: [{ op: 'drill', time_s: 12, t0: 0, t1: 12, tool: 'T2' }, 'junk', { op: 'profile', t0: 12, t1: 42 }] }, 7],
    tools: [{ id: 'T2', type: 'drill', diameter_mm: 5 }],
    findings: [{ check: 'gouge', severity: 'error', summary: 'Cuts into the part' }, { severity: 'error' }, 'junk'], verdict: 'bad' } });
  const job = readCamJob(root)!;
  expect(job.setups).toHaveLength(1);
  expect(job.setups[0]).toMatchObject({ id: 'setup-1', plain: 'setup-1', timeS: 42, axis: [0, 0, 1] });
  expect(job.operations.map((op: any) => [op.index, op.plain, op.t0, op.t1, op.toolDiameterMm, op.toolType])).toEqual([[0, 'drill', 0, 12, 5, 'drill'], [1, 'profile', 12, 42, null, '']]);
  expect(job.operations[0].summary).toBe('drill');
  expect(job.findings).toEqual([{ check: 'gouge', level: 'error', message: 'Cuts into the part', operation: null, operations: [], at: null }]);
  expect(job.verdict).toEqual({ status: 'fix', headline: '', errors: 1, warnings: 0, gcode: '' });
  expect([job.durationS, job.post]).toEqual([42, '']);
});

it('resolves the part the job was planned from against the GLB, and says durations plainly', () => {
  expect(camSourcePath('/work/out/part.cam.glb', 'part.step')).toBe('/work/out/part.step');
  expect(camSourcePath('/work/out/part.cam.glb', '../src/part.step')).toBe('/work/src/part.step');
  expect(camSourcePath('/work/out/part.cam.glb', '/abs/part.step')).toBe('/abs/part.step');
  expect(camSourcePath('/work/out/part.cam.glb', '')).toBe('');
  expect([0, 0.4, 35, 59.4, 60, 2520, 3900, 7200].map(formatDuration)).toEqual(['0 s', '1 s', '35 s', '59 s', '1 min', '42 min', '1 h 5 min', '2 h']);
});

it('reads the job\'s tools in the order the program uses them, each with the speeds its operations run it at', () => {
  const job = readCamJob(camScene())!;
  expect(job.tools).toEqual([
    { id: 'T1', label: 'T1', plain: '6 mm flat', type: 'flat', diameterMm: 6, operations: [0, 1, 2], rpm: [13260, 13260], feedMmMin: [1061, 1083] },
    { id: 'T2', label: 'T2', plain: '6 mm drill', type: 'drill', diameterMm: 6, operations: [3], rpm: [7960, 7960], feedMmMin: [955, 955] }]);
  expect(toolSpeeds(job.tools[0])).toBe('13,260 rpm · 1,061–1,083 mm/min');
  expect(toolSpeeds({ rpm: null, feedMmMin: null })).toBe('');
  // A listed tool no operation runs comes last, named from its size and type where it has no plain words.
  const extras = camExtras();
  extras.tools.push({ id: 'T7', type: 'ball', diameter_mm: 3 });
  expect(readCamJob(camScene({ extras }))!.tools.map((tool: any) => [tool.label, tool.plain, tool.operations])).toEqual([
    ['T1', '6 mm flat', [0, 1, 2]], ['T2', '6 mm drill', [3]], ['T7', '3 mm ball', []]]);
});

it('counts the tool changes from the operations in program order', () => {
  const job = readCamJob(camScene())!;
  expect(job.toolChanges).toBe(1);
  expect(jobSummary(job)).toBe('1 tool change · grbl controller');
  // Back to T1 after the drill: two changes.
  const extras = camExtras();
  extras.setups[0].operations[2].tool = 'T2';
  extras.setups[0].operations[3].tool = 'T1';
  expect(readCamJob(camScene({ extras }))!.toolChanges).toBe(2);
  expect([0, 1, 2].map((count) => toolChangeWords(count))).toEqual(['No tool changes', '1 tool change', '2 tool changes']);
});
